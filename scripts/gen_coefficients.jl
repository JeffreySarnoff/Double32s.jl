# scripts/gen_coefficients.jl — generates src/math/coefficients.jl.
#
# Run:  julia scripts/gen_coefficients.jl
#
# Design section 20.3 requires elementary-function coefficients "stored as
# `Double32` pairs". This script is the only place they are produced, and it
# produces them from 400-bit `BigFloat` values, never from `Float64` literals —
# a `Float64` coefficient is already wrong in the 54th bit, which is inside the
# range a `Double32` can represent.
#
# **Every constant is emitted as a `reinterpret` bit pattern, never as a decimal
# literal.** This is the same rule the capability probe follows and for the same
# reason: a decimal literal has to round-trip through the parser, and a
# coefficient that is one ulp off is a defect that no test of the *generator*
# would catch. Bit patterns are exact by construction.

import Pkg
Pkg.activate(joinpath(@__DIR__, ".."); io = devnull)

using Printf

setprecision(BigFloat, 400)

const OUT = joinpath(@__DIR__, "..", "src", "math", "coefficients.jl")

"""
Split a `BigFloat` into the canonical `Double32` pair nearest to it: the high
word is the nearest `Float32`, the low word the nearest `Float32` to the
remainder. This is exactly what `canonicalize` would produce, computed in
`BigFloat` so no double rounding occurs.
"""
function d32_words(v::BigFloat)
    iszero(v) && return (0.0f0, 0.0f0)      # never emit a negative zero
    hi = Float32(v)
    isfinite(hi) || error("coefficient overflows Float32: $v")
    lo = Float32(v - big(hi))
    return hi, lo
end

bits(x::Float32) = reinterpret(UInt32, x)

fmt(x::Float32) = @sprintf("reinterpret(Float32, 0x%08x)", bits(x))

function emit_d32(io, name, v::BigFloat, comment)
    hi, lo = d32_words(v)
    println(io, "\"\"\"")
    println(io, "    Double32s.$name")
    println(io)
    println(io, comment)
    println(io)
    @printf(io, "Decimal value for reading only: `%.20g`.\n", Float64(v))
    println(io, "\"\"\"")
    println(io, "const $name = raw($(fmt(hi)), $(fmt(lo)))")
    println(io)
    return nothing
end

function emit_f32(io, name, x::Float32, comment)
    println(io, "# $comment")
    println(io, "const $name = $(fmt(x))")
    return nothing
end

# A table indexed by position rather than polynomial degree.
function emit_table(io, name, vs::Vector{BigFloat}, comment)
    println(io, "\"\"\"")
    println(io, "    Double32s.$name")
    println(io)
    println(io, comment)
    println(io, "\"\"\"")
    println(io, "const $name = (")
    for v in vs
        hi, lo = d32_words(v)
        @printf(io, "    raw(%s, %s),  # %.17g\n", fmt(hi), fmt(lo), Float64(v))
    end
    println(io, ")")
    println(io)
    return nothing
end

function emit_f32_table(io, name, vs::Vector{Float32}, comment)
    println(io, "\"\"\"")
    println(io, "    Double32s.$name")
    println(io)
    println(io, comment)
    println(io, "\"\"\"")
    println(io, "const $name = (")
    for v in vs
        @printf(io, "    %s,  # %.9g\n", fmt(v), Float64(v))
    end
    println(io, ")")
    println(io)
    return nothing
end

function emit_tuple(io, name, vs::Vector{BigFloat}, comment)
    println(io, "\"\"\"")
    println(io, "    Double32s.$name")
    println(io)
    println(io, comment)
    println(io)
    println(io, "$(length(vs)) coefficients, index `n` holding the coefficient of the")
    println(io, "degree-`n-1` term of the Horner form.")
    println(io, "\"\"\"")
    println(io, "const $name = (")
    for v in vs
        hi, lo = d32_words(v)
        @printf(io, "    raw(%s, %s),  # %.17g\n", fmt(hi), fmt(lo), Float64(v))
    end
    println(io, ")")
    println(io)
    return nothing
end

open(OUT, "w") do io
    println(io, "# src/math/coefficients.jl")
    println(io, "#")
    println(io, "# GENERATED by scripts/gen_coefficients.jl — do not edit by hand.")
    println(io, "#")
    println(io, "# Every value is a `reinterpret` bit pattern computed from a 400-bit")
    println(io, "# `BigFloat`. Design section 20.3: coefficients are stored as `Double32`")
    println(io, "# pairs, and they are produced from a reference precision rather than from")
    println(io, "# `Float64` literals, which are already wrong in the 54th bit.")
    println(io)

    # ------------------------------------------------------------- constants ---
    ln2 = log(big(2))
    emit_d32(io, "LN2", ln2, "Natural logarithm of 2, as a canonical `Double32` pair.")
    emit_d32(io, "INV_LN2", inv(ln2), "`1/ln(2)`, the multiplier for `exp` range reduction.")
    emit_d32(io, "LN10", log(big(10)), "Natural logarithm of 10.")
    emit_d32(io, "LOG10_E", inv(log(big(10))), "`log10(e)`.")

    # Cody–Waite split of ln2: LN2_HI holds a Float32 with trailing zero bits so
    # that `k * LN2_HI` is exact for every |k| that `exp` can reach.
    hi32 = Float32(ln2)
    hi_trunc = reinterpret(Float32, bits(hi32) & 0xffff0000)   # 8 significand bits
    println(io, """
    # Cody–Waite split of ln(2) for `exp` argument reduction.
    #
    # `LN2_C1` keeps only the top 8 significand bits, so `k * LN2_C1` is EXACT in
    # `Float32` for every |k| < 2^15 — far beyond the |k| <= 128 that `exp` can
    # reach before overflow. The remainder is carried in a full `Double32`, so
    # `x - k*LN2_C1 - k*LN2_C2` loses nothing to cancellation even when the two
    # leading terms agree to 24 bits.""")
    emit_f32(io, "LN2_C1", hi_trunc, "top 8 significand bits of ln(2)")
    println(io)
    emit_d32(io, "LN2_C2", ln2 - big(hi_trunc),
             "Remainder of `ln(2)` after `Double32s.LN2_C1`, as a `Double32` pair.")

    # `exp10` must reduce in its OWN variable, not by multiplying into `exp`.
    # `exp10(x) = 2^k * 10^r` with `k = round(x*log2(10))` and
    # `r = x - k*log10(2)`, so `|r| <= log10(2)/2 = 0.1505` and `r*ln(10)` lands
    # inside the `expm1` kernel's band. Reducing instead by `exp(x*ln10)` makes
    # the argument's absolute error grow with `x`, and `exp` converts absolute
    # argument error straight into relative result error — measured at
    # **56 ulp48** before this was fixed.
    emit_d32(io, "LOG2_10", log(big(10)) / log(big(2)), "`log2(10)`, the multiplier for `exp10` range reduction.")
    emit_d32(io, "LOG10_2", log(big(2)) / log(big(10)), "`log10(2)`, the exact-integer term for `log10`.")
    l102 = log(big(2)) / log(big(10))
    l102_hi = reinterpret(Float32, bits(Float32(l102)) & 0xffff0000)
    println(io, "# Cody–Waite split of log10(2) for `exp10` argument reduction.")
    emit_f32(io, "LOG10_2_C1", l102_hi, "top 8 significand bits of log10(2)")
    println(io)
    emit_d32(io, "LOG10_2_C2", l102 - big(l102_hi),
             "Remainder of `log10(2)` after `Double32s.LOG10_2_C1`.")

    # -------------------------------------------------------------- exp table ---
    # exp reduces with k2 = round(x * 32/ln2): exp(x) = 2^(k2>>5) * 2^(j/32) *
    # e^r with j = k2 & 31 and |r| <= ln2/64 = 0.01083. The table carries
    # 2^(j/32) as pairs; the inverse table carries 2^(-j/32) so that e^{-x} is
    # available without a division (sinh, cosh, tanh share one reduction).
    emit_table(io, "EXP32_TABLE",
        [big(2.0)^(BigFloat(j) / 32) for j in 0:31],
        "`2^(j/32)` for `j = 0..31`, as `Double32` pairs: the `exp` reduction\n" *
        "table. Entry `j + 1` holds `2^(j/32)`.")
    emit_table(io, "EXP32_INV_TABLE",
        [big(2.0)^(-BigFloat(j) / 32) for j in 0:31],
        "`2^(-j/32)` for `j = 0..31`: gives `e^{-x}` from the same reduction\n" *
        "with no division. Entry `j + 1` holds `2^(-j/32)`.")

    emit_f32(io, "INVLN2_32", Float32(32 / ln2), "32/ln(2), the exp table-reduction multiplier")
    println(io)
    # Cody–Waite split of ln(2)/32, derived by exact 2^-5 scaling of the ln(2)
    # split: k2 * LN2_32_C1 is exact in Float32 for |k2| < 2^15, and exp's k2
    # never exceeds 4113.
    ln2_32_c1 = hi_trunc * 2.0f0^-5
    emit_f32(io, "LN2_32_C1", ln2_32_c1, "top 8 significand bits of ln(2)/32")
    println(io)
    emit_d32(io, "LN2_32_C2", ln2 / 32 - big(ln2_32_c1),
             "Remainder of `ln(2)/32` after `Double32s.LN2_32_C1`.")
    emit_f32(io, "L10_32", Float32(32 * log(big(10)) / ln2), "32*log2(10), the exp10 table-reduction multiplier")
    println(io)
    l10_32_c1 = l102_hi * 2.0f0^-5
    emit_f32(io, "L10_32_C1", l10_32_c1, "top 8 significand bits of log10(2)/32")
    println(io)
    emit_d32(io, "L10_32_C2", l102 / 32 - big(l10_32_c1),
             "Remainder of `log10(2)/32` after `Double32s.L10_32_C1`.")

    # ------------------------------------------------------------------ expm1 ---
    # expm1(r) = r * P(r), P(r) = sum_{n>=0} r^n / (n+1)!
    # |r| <= ln2 = 0.69315: the direct-series band of `expm1`. Past it the
    # subtraction `exp(x) - 1` no longer cancels more than one bit. The degree
    # is chosen so the first omitted term is below 2^-52 relative to P(0) = 1.
    nexp = 0
    r = big(log(big(2)))
    while r^nexp / factorial(big(nexp + 1)) > big(2.0)^-52
        nexp += 1
    end
    expm1_c = [inv(factorial(big(n + 1))) for n in 0:nexp]
    emit_tuple(io, "EXPM1_COEFFS", expm1_c,
        "Horner coefficients for `expm1(r)/r = sum r^n/(n+1)!` on `|r| <= ln(2)`.\n\n" *
        "The band is `expm1`'s direct-series region: past `ln 2` the value of\n" *
        "`exp(x)` is at least `2` (or at most `1/2`), so `exp(x) - 1` cancels at\n" *
        "most one bit and the table path takes over. The degree is chosen so the\n" *
        "first omitted term is below `2^-52` relative to the leading `1`.")

    # `log1p` for small `x` must avoid `x/(2+x)`: this package's division carries
    # 4.00 ulp48, and that error passes straight into the result — measured
    # **4.06 ulp48**, i.e. log1p was division-limited in exactly the region it
    # exists to serve. A direct series in `x` has no division at all. The band
    # only needs to cover the log reduction's residual |r| <= 0.0222; larger
    # arguments go through the log table.
    xmax = big(0.0222)
    nl1p = 0
    while xmax^nl1p / (nl1p + 1) > big(2.0)^-52
        nl1p += 1
    end
    log1p_c = [(-1)^n / big(n + 1) for n in 0:nl1p]
    emit_tuple(io, "LOG1P_COEFFS", log1p_c,
        "Horner coefficients for `log1p(r)/r = sum (-1)^n r^n/(n+1)` on\n" *
        "`|r| <= 0.0222` — the residual band of the log table reduction, shared\n" *
        "by the whole log family and by `log1p` itself near zero.\n\n" *
        "A series rather than the `atanh` form because that form needs `x/(2+x)`\n" *
        "and this package's division carries 4.00 ulp48 — which became the whole\n" *
        "error of `log1p` near zero, where it matters most.")

    # -------------------------------------------------------------- log table ---
    # m in [sqrt2/2, sqrt2) lands in bin i = round(m*32), i = 23..45. With
    # c = fl32(32/i), the residual r = m*c - 1 is computed exactly (two
    # two_prods and exact sums) and satisfies |r| <= 0.0222, inside the
    # LOG1P_COEFFS band. -log(c) is tabulated per base so the exact exponent
    # contribution stays separate (log2/log10 keep `k` exact).
    log_c = [Float32(32 / big(i)) for i in 23:45]
    emit_f32_table(io, "LOG_TABLE_C", log_c,
        "`fl32(32/i)` for bins `i = 23..45` of the log reduction; entry `i - 22`.\n" *
        "`r = m*c - 1` is exact and `|r| <= 0.0222`.")
    emit_table(io, "LOG_TABLE_LN", [-log(big(c)) for c in log_c],
        "`-log(c)` for each `LOG_TABLE_C` entry, as `Double32` pairs.")
    emit_table(io, "LOG_TABLE_L2", [-log(big(c)) / ln2 for c in log_c],
        "`-log2(c)` for each `LOG_TABLE_C` entry.")
    emit_table(io, "LOG_TABLE_L10", [-log(big(c)) / log(big(10)) for c in log_c],
        "`-log10(c)` for each `LOG_TABLE_C` entry.")

    # -------------------------------------------------------------------- log ---
    # log(m) = 2*atanh(s), s = (m-1)/(m+1), |s| <= (sqrt2-1)/(sqrt2+1) = 0.17157
    smax = (sqrt(big(2)) - 1) / (sqrt(big(2)) + 1)
    nlog = 0
    while smax^(2 * nlog) / (2 * nlog + 1) > big(2.0)^-52
        nlog += 1
    end
    atanh_c = [inv(big(2 * n + 1)) for n in 0:nlog]
    emit_tuple(io, "ATANH_COEFFS", atanh_c,
        "Horner coefficients in `s^2` for `atanh(s)/s = sum s^(2n)/(2n+1)`.\n\n" *
        "`log(m) = 2*atanh((m-1)/(m+1))` with `m` reduced to `[sqrt(2)/2, sqrt(2))`,\n" *
        "so `|s| <= 0.171573` and the series converges in `s^2 <= 0.029437`.")

    # ------------------------------------------------------------- hyperbolic ---
    # `tanh` is the one hyperbolic function that cannot avoid a division in its
    # general form (`t/(t+2)` with `t = expm1(2x)`), and this package's `/`
    # carries 4.00 ulp48. A series in `x^2` removes it for small `x`, which is
    # where `tanh` is used as an activation and where relative accuracy matters.
    #
    # The coefficients are obtained by dividing the `sinh(x)/x` series by the
    # `cosh(x)` series, both in `y = x^2`, rather than through Bernoulli
    # numbers: the recurrence is three lines and cannot be mistranscribed.
    ytanh = big(0.35)^2
    ndiv = 40
    a = [inv(factorial(big(2n + 1))) for n in 0:ndiv]      # sinh(x)/x
    b = [inv(factorial(big(2n))) for n in 0:ndiv]          # cosh(x)
    t = zeros(BigFloat, ndiv + 1)
    for n in 0:ndiv
        acc = a[n + 1]
        for k in 1:n
            acc -= b[k + 1] * t[n - k + 1]
        end
        t[n + 1] = acc                                     # b[1] == 1
    end
    ntanh = 0
    while abs(t[ntanh + 1]) * ytanh^ntanh > big(2.0)^-52
        ntanh += 1
    end
    emit_tuple(io, "TANH_COEFFS", t[1:(ntanh + 1)],
        "Horner coefficients in `x^2` for `tanh(x)/x` on `|x| <= 0.35`.\n\n" *
        "Obtained by dividing the `sinh(x)/x` series by the `cosh(x)` series in\n" *
        "`BigFloat`, so no Bernoulli-number table has to be transcribed.")

    # `asinh` near zero: `log1p(x + x^2/(1 + sqrt(1+x^2)))` needs a division and
    # a square root, both of which put a floor under the error. The series does
    # not. asinh(x)/x = sum (-1)^n (2n)! / (4^n (n!)^2 (2n+1)) * x^(2n).
    yas = big(0.35)^2
    asinh_c = BigFloat[]
    n = 0
    while true
        c = (-1)^n * factorial(big(2n)) /
            (big(4)^n * factorial(big(n))^2 * (2n + 1))
        push!(asinh_c, c)
        abs(c) * yas^n <= big(2.0)^-52 && break
        n += 1
        n > 60 && break
    end
    emit_tuple(io, "ASINH_COEFFS", asinh_c,
        "Horner coefficients in `x^2` for `asinh(x)/x` on `|x| <= 0.35`.\n\n" *
        "Used instead of `log1p(x + x^2/(1 + sqrt(1+x^2)))` for small `x`, which\n" *
        "needs both a division and a square root.")

    # Dedicated sinh/cosh series on |x| <= 1: all-positive terms, no exp call,
    # no subtraction, and the band edge keeps the large-|x| path's
    # e^x - e^{-x} cancellation under half a bit (e^{-2} = 0.135).
    nsinh_ = 0
    while inv(factorial(big(2 * nsinh_ + 1))) > big(2.0)^-52
        nsinh_ += 1
    end
    emit_tuple(io, "SINH_COEFFS", [inv(factorial(big(2n + 1))) for n in 0:nsinh_],
        "Horner coefficients in `x^2` for `sinh(x)/x = sum x^(2n)/(2n+1)!` on\n" *
        "`|x| <= 1`.")
    ncosh_ = 0
    while inv(factorial(big(2 * ncosh_))) > big(2.0)^-52
        ncosh_ += 1
    end
    emit_tuple(io, "COSH_COEFFS", [inv(factorial(big(2n))) for n in 0:ncosh_],
        "Horner coefficients in `x^2` for `cosh(x) = sum x^(2n)/(2n)!` on\n" *
        "`|x| <= 1`.")

    # ------------------------------------------------------------------- trig ---
    piby2 = big(pi) / 2
    emit_d32(io, "TWO_OVER_PI", 2 / big(pi), "`2/π`, the multiplier for trigonometric argument reduction.")

    # Three-word Cody–Waite split of pi/2. Each word keeps 8 significand bits
    # except the last, which absorbs the remainder as a full Double32.
    p1 = reinterpret(Float32, bits(Float32(piby2)) & 0xffff0000)
    rem1 = piby2 - big(p1)
    p2 = reinterpret(Float32, bits(Float32(rem1)) & 0xffff0000)
    rem2 = rem1 - big(p2)
    println(io, """
    # Three-word Cody–Waite split of π/2 for trigonometric argument reduction.
    #
    # `PIO2_C1` and `PIO2_C2` keep 8 significand bits each, so `k * PIO2_C1` and
    # `k * PIO2_C2` are both EXACT in `Float32` for |k| < 2^15. The remainder is a
    # full `Double32`. Together they carry about 72 bits of π/2, which is what
    # bounds the argument range over which reduction is exact — see
    # `Double32s.TRIG_ARG_LIMIT`.""")
    emit_f32(io, "PIO2_C1", p1, "top 8 significand bits of π/2")
    println(io)
    emit_f32(io, "PIO2_C2", p2, "next 8 significand bits of π/2")
    println(io)
    emit_d32(io, "PIO2_C3", rem2,
             "Remainder of `π/2` after `PIO2_C1 + PIO2_C2`, as a `Double32` pair.")

    # sin(r)/r = sum (-1)^n r^(2n)/(2n+1)!, cos(r) = sum (-1)^n r^(2n)/(2n)!
    # |r| <= pi/4 = 0.7854
    rmax = big(pi) / 4
    nsin = 0
    while rmax^(2 * nsin) / factorial(big(2 * nsin + 1)) > big(2.0)^-52
        nsin += 1
    end
    sin_c = [(-1)^n / factorial(big(2 * n + 1)) for n in 0:nsin]
    emit_tuple(io, "SIN_COEFFS", sin_c,
        "Horner coefficients in `r^2` for `sin(r)/r` on `|r| <= π/4`.")

    ncos = 0
    while rmax^(2 * ncos) / factorial(big(2 * ncos)) > big(2.0)^-52
        ncos += 1
    end
    cos_c = [(-1)^n / factorial(big(2 * n)) for n in 0:ncos]
    emit_tuple(io, "COS_COEFFS", cos_c,
        "Horner coefficients in `r^2` for `cos(r)` on `|r| <= π/4`.")

    # atan(t)/t = sum (-1)^n t^(2n)/(2n+1), |t| <= tan(pi/12) = 2-sqrt(3)
    tmax = 2 - sqrt(big(3))
    natan = 0
    while tmax^(2 * natan) / (2 * natan + 1) > big(2.0)^-52
        natan += 1
    end
    atan_c = [(-1)^n / big(2 * n + 1) for n in 0:natan]
    emit_tuple(io, "ATAN_COEFFS", atan_c,
        "Horner coefficients in `t^2` for `atan(t)/t` on `|t| <= 2-sqrt(3) = tan(π/12)`.")

    emit_d32(io, "PI_D32", big(pi), "`π` as a canonical `Double32` pair.")
    emit_d32(io, "PIO2_D32", piby2, "`π/2` as a canonical `Double32` pair.")
    emit_d32(io, "PIO4_D32", big(pi) / 4, "`π/4` as a canonical `Double32` pair.")
    emit_d32(io, "SQRT3_D32", sqrt(big(3)), "`sqrt(3) = tan(π/3)`, for the `atan` argument reduction.")
    emit_d32(io, "TAN_PI6_D32", tan(big(pi) / 6), "`tan(π/6)`, for the `atan` argument reduction.")
    emit_d32(io, "PI6_D32", big(pi) / 6, "`π/6`, the first `atan` rotation angle.")
    emit_d32(io, "PI3_D32", big(pi) / 3, "`π/3`, the second `atan` rotation angle.")
end

@info "wrote $OUT"
